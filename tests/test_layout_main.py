SPECS = ROOT / "docs" / "examples" / "specs"
NS = "{http://www.w3.org/2000/svg}"


def spec_dict(name):
    yaml, loader = layout_spec._yaml_loader()          # YAML 1.2 booleans: `on:` stays a key
    return yaml.load((SPECS / f"{name}.layout.yaml").read_text(encoding="utf-8"), Loader=loader)


def built(d_or_name, **kw):
    d = spec_dict(d_or_name) if isinstance(d_or_name, str) else d_or_name
    spec = layout_spec.load(copy.deepcopy(d))
    return spec, layout.build(spec, [], {}, None, "x.layout.yaml", **kw)


class Emit(unittest.TestCase):
    def test_header_and_subset(self):
        spec, b = built("nfw-reference-architecture")
        text = b.svg.decode("utf-8")
        lines = text.splitlines()
        self.assertTrue(lines[0].startswith(f'<svg viewBox="0 0 {M.fmt_num(b.geom.canvas_w)} '
                                            f'{M.fmt_num(b.geom.canvas_h)}"'))
        self.assertIn(f'font-family="{K.FONT_FAMILY_DEFAULT}"', lines[0])
        self.assertIn("<!-- generated by layout.py from x.layout.yaml — edit the spec and re-run", lines[1])
        self.assertIn('<marker id="arrowStart"', text)          # nfw has <-> edges
        root = ET.fromstring(b.svg)
        kids = list(root)
        self.assertEqual(kids[0].tag, NS + "defs")
        self.assertEqual((kids[1].tag, kids[1].get("fill")), (NS + "rect", "#FFFFFF"))
        ids = [g.get("id") for g in root.iter(NS + "g")]
        self.assertEqual(len(ids), len(set(ids)), "every <g id> unique")
        for g in root.iter(NS + "g"):
            self.assertEqual(set(g.keys()), {"id"}, "svg2pptx takes <g> with id only")
            kind, ref, part = M.split_eid(g.get("id"))
            self.assertIn(kind, ("group", "node", "edge", "note", "raw"))

    def test_no_arrow_start_without_two_way_edges(self):
        spec, b = built("nlb-reference-architecture")
        self.assertNotIn(b"arrowStart", b.svg)

    def test_z_order(self):
        spec, b = built("tgw-reference-architecture")
        root = ET.fromstring(b.svg)
        order = {"group": 0, "node": 1, "edge": 2, "note": 5}
        seen = []
        for g in root.iter(NS + "g"):
            kind, _, part = M.split_eid(g.get("id"))
            seen.append({"label": 3, "badge": 4}.get(part, order[kind]))
        self.assertEqual(seen, sorted(seen))

    def test_deterministic(self):
        a = built("bedrock-dx-reference-architecture")[1].svg
        b = built("bedrock-dx-reference-architecture")[1].svg
        self.assertEqual(a, b)


class Raw(unittest.TestCase):
    def test_placeholders_and_layers(self):
        d = spec_dict("example")
        d["raw"] = [{"layer": "above", "svg": '<text x="{alb.cx}" y="{alb.y1+40}" font-size="12" '
                                              'fill="#545B64" text-anchor="middle">note</text>'},
                    {"layer": "below", "svg": '<rect x="{vpc.x0}" y="{vpc.y0}" width="4" height="4" fill="#FFFFFF"/>'}]
        spec, b = built(d)
        alb = b.geom.nodes["alb"]
        text = b.svg.decode("utf-8")
        self.assertIn(f'<text x="{M.fmt_num(alb.cx)}" y="{M.fmt_num(alb.icon.y1 + 40)}"', text)
        root = ET.fromstring(b.svg)
        gids = [g.get("id") for g in root.iter(NS + "g")]
        self.assertEqual(gids[0], "raw:1")                 # below: right after the background
        self.assertEqual(gids[-1], "raw:0")                # above: last

    def test_subset_rejected(self):
        d = spec_dict("example")
        d["raw"] = [{"layer": "above", "svg": '<path d="M0,0 L1,1"/>'}]
        with self.assertRaises(M.SpecError) as cm:
            built(d)
        self.assertIn("<path> is not in the draft subset", cm.exception.problems[0])
        self.assertEqual(layout.raw_problems('<g fill="red"><rect x="1" y="1" width="2" height="2"/></g>'),
                         ["<g> carries fill; svg2pptx takes only id (and translate)"])


class PadTop(unittest.TestCase):
    def test_pad_top_moves_icons_down(self):
        d = spec_dict("example")
        for g in d["groups"]:
            if g["id"] == "appsn":
                g["pad_top"] = 80
        spec, b = built(d)
        for n in (1, 2):
            top = b.geom.groups[f"appsn.{n}"].rect.y0
            self.assertGreaterEqual(b.geom.nodes[f"ec2.{n}"].icon.y0 - top, 80 - 0.01)


class Feedback(unittest.TestCase):
    def test_bracket(self):
        spec, b = built("nfw-reference-architecture")
        g = b.geom
        a, c, cur = layout.bracket(g, "x", (g.cols["eni"] + g.cols["fw"]) / 2)
        self.assertEqual((a, c), ("col:eni", "col:fw"))
        self.assertAlmostEqual(cur, g.cols["fw"] - g.cols["eni"])
        self.assertIsNone(layout.bracket(g, "x", g.cols["inet"] + 1))

    def test_widen_a_crowded_badge(self):
        """A problem near a vertical border widens the column gap it sits in."""
        spec, b = built("nfw-reference-architecture")
        g = b.geom
        x = (g.cols["eni"] + g.cols["fw"]) / 2
        seg = {"p": (x, 0), "q": (x, 10), "kind": "border", "el": None}
        txt = {"box": (x - 5, 100, x + 5, 110), "el": None}
        iss = CL.Issue("TEXT AT BORDER", "TEXT AT BORDER  '3' ...", [], {"t": txt, "s": seg, "clear": 8})
        extra, skip = {}, {}
        self.assertTrue(layout.feedback(b, [layout.Problem(iss, ["edge:3:badge"], [txt, seg])], extra, skip))
        (key, r), = extra.items()
        self.assertEqual(key, ("x", "col:eni", "col:fw"))
        self.assertAlmostEqual(r.d, g.cols["fw"] - g.cols["eni"] + layout.WIDEN)

    def test_line_problem_skips_a_candidate_first(self):
        spec, b = built("nfw-reference-architecture")
        seg = {"p": (0, 0), "q": (10, 0), "kind": "connector", "el": None}
        txt = {"box": (2, -3, 8, 3), "el": None}
        iss = CL.Issue("LINE OVER TEXT", "LINE OVER TEXT ...", [], {"t": txt, "s": seg})
        extra, skip = {}, {}
        layout.feedback(b, [layout.Problem(iss, ["edge:2", "node:tgw"], [txt, seg])], extra, skip)
        self.assertEqual((extra, skip), ({}, {2: 1}))


class LabelOnLine(unittest.TestCase):
    def test_no_room_above_or_below_puts_the_label_on_its_line(self):
        """No room above (a sub-caption) nor below (an icon): the label sits on its line over
        a background rect, both in the top layer, and the draft still checks clean."""
        d = {"name": "t", "cols": ["a"], "rows": ["r"],
             "nodes": [{"id": "x", "icon": "service/AWS-Lambda", "label": "Fn A", "xy": [60, 200]},
                       {"id": "y", "icon": "service/AWS-Lambda", "label": "Fn B", "xy": [300, 200]},
                       {"id": "z", "icon": "service/Amazon-Simple-Storage-Service", "label": "Bucket",
                        "sub": ["a long sub-caption line"], "xy": [180, 124]},
                       {"id": "w", "icon": "service/Amazon-Simple-Storage-Service", "label": "Logs",
                        "xy": [180, 250]}],
             "edges": [{"e": "x -> y", "label": "HTTPS :443", "shape": "H"}]}
        spec, b = built(d)
        top = [e for e in b.elements if e.z == K.Z_LABEL_TOP]
        self.assertEqual([e.kind for e in top], ["rect", "text"])
        rect, text = top
        self.assertEqual(rect.attrs["fill"], K.LABEL_BG)
        self.assertLess(rect.attrs["y"], 200)
        self.assertGreater(rect.attrs["y"] + rect.attrs["height"], 200)       # the line runs under it
        self.assertEqual(max(e.z for e in b.elements), K.Z_LABEL_TOP)
        self.assertTrue(any("sits on its line" in w for w in b.warnings), b.warnings)
        self.assertEqual([i.msg for i in CL.run_checks(ET.fromstring(b.svg))], [])


class CLI(unittest.TestCase):
    def run_cli(self, *args):
        p = subprocess.run([sys.executable, str(ROOT / "scripts" / "layout.py"), *map(str, args)],
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True, cwd=str(ROOT))
        return p.returncode, p.stdout

    def test_examples_ok_and_fast(self):
        with tempfile.TemporaryDirectory() as tmp:
            for spec in sorted(SPECS.glob("*.layout.yaml")):
                out = Path(tmp) / "d.draft.svg"
                t0 = time.time()
                rc, text = self.run_cli(spec, "-o", out)
                dt = time.time() - t0
                self.assertEqual((rc, text.strip().splitlines()[-1]), (0, "Layout OK"), f"{spec.name}:\n{text}")
                self.assertLess(dt, 2.5, f"{spec.name} took {dt:.2f}s")    # 2 s target + interpreter start
                lines, n = CL.run_file(str(out), False)
                self.assertEqual(lines[-1], "Layout OK", spec.name)

    def test_summary_and_explain(self):
        with tempfile.TemporaryDirectory() as tmp:
            rc, text = self.run_cli(SPECS / "nlb-mtls-reference-architecture.layout.yaml", "-o",
                                    Path(tmp) / "a.svg", "--explain")
        self.assertEqual(rc, 0)
        self.assertIn("canvas: ", text)
        self.assertIn("12px text → ", text)
        self.assertIn("note: pane, 3 steps", text)
        self.assertIn("icons (8 nodes): ", text)
        self.assertIn("x col ", text)

    def test_slide_mode_reports_pt(self):
        with tempfile.TemporaryDirectory() as tmp:
            rc, text = self.run_cli(SPECS / "nlb-reference-architecture.layout.yaml", "-o", Path(tmp) / "s.svg",
                                    "--mode", "slide", "--no-check")
        self.assertEqual(rc, 0, text)
        self.assertIn("(slide)", text)
        self.assertIn("check skipped", text)

    def test_spec_error_exit_1(self):
        with tempfile.TemporaryDirectory() as tmp:
            bad = Path(tmp) / "bad.layout.json"
            bad.write_text('{"name": "bad", "cols": ["a"], "rows": ["r"], "nodes": [{"id": "x", "icon": "nope/none", '
                           '"label": "X", "at": ["a", "r"]}]}', encoding="utf-8")
            rc, text = self.run_cli(bad, "-o", Path(tmp) / "bad.svg")
        self.assertEqual(rc, 1)
        self.assertIn("nodes[0]", text)
        self.assertTrue(text.strip().splitlines()[-1].endswith("in the spec"))

    def test_main_in_process(self):
        with tempfile.TemporaryDirectory() as tmp:
            buf = io.StringIO()
            with redirect_stdout(buf):
                rc = layout.main([str(SPECS / "example.layout.yaml"), "-o", str(Path(tmp) / "e.svg")])
            self.assertEqual(rc, 0)
            self.assertEqual(buf.getvalue().strip().splitlines()[-1], "Layout OK")


if __name__ == "__main__":
    unittest.main(verbosity=1)
