class Feedback(unittest.TestCase):
    def test_bracket(self):
        spec, b = built("nfw-reference-architecture")
        g = b.geom
        a, c, cur = layout.bracket(g, "x", (g.cols["eni"] + g.cols["fw"]) / 2)
